// Regression checks consume real frozen UI/API observations, not a simulated
// discovery score. They do not establish exploration-policy or RSI benefit.
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {challengeIdentity,uncoveredReplayType} from './reference-challenge-identity.mjs';
const base=fileURLToPath(new URL('./evidence/english-third-v1/',import.meta.url));
const read=name=>JSON.parse(readFileSync(base+name,'utf8'));
const session=read('session.json').session;
const rows=[...read('replay-01.json').observed,...read('replay-02.json').observed];
const accepted=rows.filter(r=>r.feedback);
assert.equal(accepted.length,12);
for(const row of accepted)assert.equal(challengeIdentity(session.challenges[row.index].content,row.identity.actual).matches,true);
const diverged=rows.find(r=>r.divergence);
assert.equal(diverged.index,12);
assert.equal(diverged.dom_type,'challenge challenge-translate');
assert.equal(session.challenges[12].content.type,'translate');
const result=challengeIdentity(session.challenges[12].content,diverged.identity.actual);
assert.equal(result.matches,false);
assert(result.reasons.includes('choice_set_changed'));
assert.equal(diverged.actions.length,0);
const prompts=[...new Set(read('hint-token-reading.json').hints.map(h=>h.parent))];
const exact=challengeIdentity(session.challenges[12].content,{...diverged.identity.actual,prompts});
assert(exact.reasons.includes('prompt_changed'));
assert(exact.prompt_check.includes('equality'));
const repeat=accepted.find(r=>r.index===9);
assert.equal(repeat.identity.actual.choices.filter(w=>w==='不要').length,2);
assert.equal(repeat.actions.filter(a=>a.word==='不要').length,2);
assert.deepEqual(repeat.actions.filter(a=>a.word==='不要').map(a=>a.occurrence),[0,1]);
console.log('PASS 12 accepted real questions, same-type adaptive divergence before action, and two distinct duplicate-token occurrences; no policy-effect claim');

const fourthBase=fileURLToPath(new URL('./evidence/english-fourth-v1/',import.meta.url));
const fourthRead=name=>JSON.parse(readFileSync(fourthBase+name,'utf8'));
const listening=fourthRead('replay-02.json').observed.find(r=>r.index===5);
const listeningExpected=fourthRead('session.json').session.challenges[5].content;
assert.equal(listening.actions.length,0);
assert.equal(listening.identity.reasons[0],'prompt_not_visible');
const playedAudio=fourthRead('audio-identity.json').media.map(m=>m.src);
assert(challengeIdentity(listeningExpected,{...listening.identity.actual,playedAudio}).matches);
assert(challengeIdentity(listeningExpected,listening.identity.actual).reasons.includes('audio_identity_unverified'));
assert(challengeIdentity(listeningExpected,{...listening.identity.actual,playedAudio:[]}).reasons.includes('audio_identity_unverified'));
assert(challengeIdentity({...listeningExpected,tts:'different-source'}, {...listening.identity.actual,playedAudio}).reasons.includes('audio_identity_unverified'));
console.log('PASS actual listening transcript is hidden; current playback source required, absent/wrong audio rejected');

const nextBase=fileURLToPath(new URL('./evidence/english-next-node-v1/',import.meta.url));
const nextRead=name=>JSON.parse(readFileSync(nextBase+name,'utf8'));
const unsupportedMatch=nextRead('replay-04.json').observed.find(r=>r.type==='listenMatch');
assert(unsupportedMatch.actions.length===0);
assert(uncoveredReplayType(unsupportedMatch.type,unsupportedMatch.dom_type));
const changedAfterDecline=nextRead('replay-03.json').observed[0];
assert.equal(uncoveredReplayType(changedAfterDecline.type,changedAfterDecline.dom_type),false);
assert(changedAfterDecline.identity.reasons.includes('type_changed'));
console.log('PASS actual unsupported audio schema distinguished from actual post-decline type drift; both preserve no-answer failure');
const actualUncoveredReview=nextRead('review-entry.json').observed[0];
assert.equal(actualUncoveredReview.coverage.kind,'uncovered_type');
assert.equal(actualUncoveredReview.actions.length,0);
assert.equal(actualUncoveredReview.identity,undefined);
console.log('PASS actual corrected replay stops at unsupported typed review before grading or misclassifying its choices');
